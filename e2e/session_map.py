import asyncio, re
from playwright.async_api import async_playwright
URL='http://localhost:4173'
fails=[]
def check(n, ok, extra=''):
    print(('PASS ' if ok else 'FAIL ')+n, extra)
    if not ok: fails.append(n)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={'width':430,'height':932},is_mobile=True,has_touch=True,reduced_motion='reduce')
        pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.wait_for_timeout(800)
        await pg.get_by_text('I understand').click(); await pg.wait_for_timeout(300)
        await pg.get_by_text('Start as Vikas').click(); await pg.get_by_text('Build my plan').click(); await pg.wait_for_timeout(700)
        await pg.get_by_role('button',name='Got it').click(); await pg.wait_for_timeout(600)
        await pg.get_by_role('button',name='I’m Vikas').click(); await pg.wait_for_timeout(600)
        await pg.goto(URL+'/?simulate=2026-11-16T07:30'); await pg.wait_for_timeout(1500)
        await pg.get_by_role('button',name='Start',exact=True).click(); await pg.wait_for_timeout(1500)
        await pg.get_by_role('button',name=re.compile('Start lifting')).click(); await pg.wait_for_timeout(1200)
        check('session open', await pg.get_by_text(re.compile('^Next:')).count()>=1)
        svgs=await pg.locator('div.fixed svg[aria-label^="Body map"]').count()
        check('front and back both shown in session', svgs==2, svgs)
        check('no Front/Back toggle in session', await pg.locator('div.fixed button', has_text=re.compile('^(Front|Back)$')).count()==0)
        if await pg.locator('div.fixed.z-\\[60\\] button', has_text='Got it').count(): await pg.locator('div.fixed.z-\\[60\\] button', has_text='Got it').first.click(); await pg.wait_for_timeout(500)
        n0=await pg.get_by_label(re.compile(r'^Mark set \d+ done')).count()
        await pg.get_by_test_id('add-set').click(); await pg.wait_for_timeout(300)
        n1=await pg.get_by_label(re.compile(r'^Mark set \d+ done')).count()
        check('add set adds a row', n1==n0+1, (n0,n1))
        await pg.get_by_test_id('remove-set').click(); await pg.wait_for_timeout(300)
        check('remove set takes it back', await pg.get_by_label(re.compile(r'^Mark set \d+ done')).count()==n0)
        await pg.get_by_test_id('add-set').click(); await pg.wait_for_timeout(300)
        await pg.get_by_test_id('session-routine').click(); await pg.wait_for_timeout(600)
        check('warm-up viewable mid-workout', await pg.get_by_test_id('warm-routine').count()==1)
        await pg.get_by_role('tab',name='Cool-down').click(); await pg.wait_for_timeout(300)
        check('cool-down viewable mid-workout', await pg.get_by_test_id('cool-routine').count()==1)
        await pg.get_by_role('button',name='Close').click(); await pg.wait_for_timeout(600)
        check('workout still running after closing', await pg.get_by_text(re.compile('^Next:')).count()>=1)
        # finish early -> cool-down -> back to the workout
        await pg.locator('button[aria-label^="Go to "]').last.click(); await pg.wait_for_timeout(500)
        await pg.get_by_role('button',name=re.compile('Finish early|Finish session')).click(); await pg.wait_for_timeout(600)
        check('cool-down reached', await pg.get_by_text('Stretch 1 of 5').count()==1)
        await pg.get_by_role('button',name='Back to workout').click(); await pg.wait_for_timeout(600)
        check('back on the workout from cool-down', await pg.get_by_role('button',name=re.compile('Finish early|Finish session')).count()==1 and await pg.get_by_text('Stretch 1 of 5').count()==0)
        check('no page errors', not errs, errs)
        await pg.screenshot(path='/home/claude/qa/103-session.png')
        await b.close()
    print('FAILS:',fails)
asyncio.run(main())
